const supportedLangs: Language[] = ['es', 'en', 'fr', 'de', 'pt', 'it', 'nl'];

export function detectLanguage(): Language {
  const browserLang = navigator.language.slice(0, 2).toLowerCase();
  if (supportedLangs.includes(browserLang as Language)) return browserLang as Language;
  return 'en';
}

